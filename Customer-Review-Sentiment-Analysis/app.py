"""
Streamlit website for Customer Review Sentiment Analysis.
First run: python train_model.py
Then: streamlit run app.py
"""
import os
import joblib
import streamlit as st

MODEL_FILE = "sentiment_model.joblib"

st.set_page_config(page_title="Customer Review Sentiment Analysis", page_icon="💬", layout="centered")
st.title("💬 Customer Review Sentiment Analysis")
st.write("Enter a product review and the trained machine-learning model will classify its sentiment.")

if not os.path.exists(MODEL_FILE):
    st.warning("The trained model is not available yet. Run `python train_model.py` first.")
    st.stop()

@st.cache_resource
def load_model():
    return joblib.load(MODEL_FILE)

model = load_model()
review = st.text_area("Enter customer review:", placeholder="Example: The product quality is excellent and I love it.")

if st.button("Analyze Sentiment", type="primary"):
    if not review.strip():
        st.error("Please enter a review before analyzing.")
    else:
        prediction = model.predict([review])[0]
        if prediction == "positive":
            st.success("Predicted Sentiment: POSITIVE 😊")
        else:
            st.error("Predicted Sentiment: NEGATIVE ☹️")
        st.caption("Prediction is generated by the model trained on the included sample dataset.")
st.divider()
st.subheader("Example reviews")
st.write("Positive: “Excellent product, very useful and easy to use.”")
st.write("Negative: “Poor quality, stopped working after two days.”")
st.caption("Academic demonstration project. Predictions depend on the quality and size of the training dataset.")
